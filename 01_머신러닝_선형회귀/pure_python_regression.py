# ------------------------------------------------------------------------------
# 📌 이 모듈에서 배우는 것 (3줄 요약)
#   1. AI가 데이터 점들을 보고 스스로 직선(y = Wx + b)을 찾아내는 원리를 배워요.
#   2. '경사하강법'으로 AI가 조금씩 정답에 가까워지는 과정을 체험해요.
#   3. 외부 라이브러리 없이, 파이썬 기본 문법만으로 AI 학습을 직접 구현해요.
# 🎒 준비물: 파이썬 3 (설치할 라이브러리가 하나도 없어요!) + 같은 폴더의 data.csv
# 📖 선수 지식: 일차함수 y = ax + b (중학교 수학이면 충분해요)
# 💡 용어 미리보기 (처음 보면 아래 뜻을 떠올려 보세요!)
#   - 가중치(W)란? AI가 "이 입력이 얼마나 중요할까?"라고 생각하는 정도예요. (직선의 기울기!)
#   - 편향(b)이란?   입력이 0이어도 나오는 기본값이에요. (직선의 y절편!)
#   - 손실함수(MSE)란? AI의 예측이 정답과 얼마나 다른지 재는 '틀린 정도 점수'예요.
#   - 경사하강법이란?  '틀린 정도'를 조금씩 줄여나가는 AI의 공부 방법이에요.
#                      안개 낀 산에서 가장 낮은 골짜기를 찾아 내려가는 것과 같아요!
# ==============================================================================
import csv

# ------------------------------------------------------------------------------
# 1. CSV 데이터 읽기: AI에게 보여줄 '문제집' 10개를 불러와요
#    (x: 공부 시간, y: 시험 점수 — "x시간 공부하면 y점을 받았대!")
# ------------------------------------------------------------------------------
x_data = []
y_data = []

with open('data.csv', 'r', encoding='utf-8') as f:
    reader = csv.reader(f)
    header = next(reader)  # 첫 줄은 제목(x, y)이니 건너뛰어요
    for row in reader:
        if row:
            x_data.append(float(row[0]))
            y_data.append(float(row[1]))

N = len(x_data)
print(f"데이터 {N}개 로드 완료: {list(zip(x_data, y_data))}\n")
# ✅ 체크포인트: 위에 (1, 2.1) ~ (10, 20.3) 10개가 보이면 성공!

# ------------------------------------------------------------------------------
# 2. 하이퍼파라미터: AI가 공부하기 전에 사람이 정해주는 '공부 규칙'이에요
# ------------------------------------------------------------------------------
learning_rate = 0.01   # 학습률: 한 번에 얼마나 크게 고칠지 정해요 (너무 크면 산에서 미끄러져요!)
epochs = 100           # 에포크: 문제집 전체를 몇 번 반복해서 풀지 정해요
W = 0.0                # 가중치(W)의 출발점: 0에서 시작해요
b = 0.0                # 편향(b)의 출발점: 0에서 시작해요
student_x = 5.5000     # [학생 실습] 테스트 입력값! "5.5시간 공부하면 몇 점일까?"를 맞혀봐요

print(f"{'Epoch':^6} | {'가중치(W)':^10} | {'편향(b)':^10} | {'손실(MSE)':^11} | {'가중치 곱(x*W)':^14} | {f'출력 Ŷ':^12}")
print("-" * 75)

# ------------------------------------------------------------------------------
# 3. 경사하강법: AI의 공부 시간! (안개 낀 산 내려가기 🏔️)
#    매 에포크마다 "틀린 정도(손실)"를 재고, W와 b를 조금씩 고쳐나가요
# ------------------------------------------------------------------------------
for epoch in range(1, epochs + 1):
    dW = 0.0
    db = 0.0
    total_loss = 0.0

    for x, y in zip(x_data, y_data):
        y_pred = W * x + b            # ① 예측: 지금 실력(W, b)으로 점수 맞혀보기
        diff = y_pred - y             # ② 오차: 예측 - 정답 (얼마나 틀렸나?)
        dW += (2.0 / N) * diff * x    # ③ 기울기 누적: W를 어느 방향으로 고칠지
        db += (2.0 / N) * diff        # ③ 기울기 누적: b를 어느 방향으로 고칠지
        total_loss += (diff ** 2) / N # ④ 손실(MSE): '틀린 정도 점수' (제곱해서 평균내요)

    W = W - learning_rate * dW  # ⑤ 공부: 기울기의 반대 방향으로 조금씩 이동 (산 내려가기!)
    b = b - learning_rate * db  # ⑤ 공부: b도 함께 조금씩 이동

    mult_val = student_x * W      # 학습된 W로 5.5시간 공부한 경우를 계산해 봐요
    student_pred = mult_val + b

    if epoch == 1 or epoch % 10 == 0 or epoch == epochs:
        print(f"{epoch:6d} | {W:10.4f} | {b:10.4f} | {total_loss:11.4f} | {mult_val:14.4f} | {student_pred:12.4f}")
# ✅ 체크포인트: 손실(MSE) 숫자가 점점 줄어들면 AI가 공부하고 있는 거예요!

print("-" * 75)

mult_result = student_x * W
final_y = mult_result + b

# ------------------------------------------------------------------------------
# 4. 동그란 노드를 통한 4단계 순전파 브리핑: 학습이 끝난 AI에게 질문하기
#    입력(x) → 가중치 곱(x*W) → 편향 더하기(+b) → 출력(Ŷ) 순서로 흘러가요
# ------------------------------------------------------------------------------
print("\n" + "="*65)
print("🧠 [AI 에듀 | 동그란 노드를 통한 4단계 가중치 곱 전파]")
print("="*65)
print(f"""
  [1단계] 입력 노드 (X)     : x = {student_x:.4f}
               │
               │  ✖ 가중치 곱 (× W: {W:.4f})
               ▼
  [2단계] 가중치 곱 (x × W) : {student_x:.2f} × {W:.4f} = {mult_result:.4f}
               │
               ▼
  [3단계] 편향 더하기 (+ b) : + {b:.4f}
               │
               │  (합산 연산 Σ: {mult_result:.4f} + {b:.4f})
               ▼
  [4단계] 출력 노드 (Ŷ)     : Ŷ = {final_y:.4f} (최종 예측값)
""")
print("="*65)
print(f"최종 선형회귀 수식: y = {W:.4f} * x + {b:.4f}")
# 🎉 수고했어요! AI가 스스로 찾아낸 직선(y = Wx + b)이 완성됐어요.
